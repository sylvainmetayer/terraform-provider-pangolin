func (r *AIProviderResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError("Unexpected Resource Configure Type", "Expected *client.Client")
		return
	}
	r.client = c
}

// buildAIProviderRequest maps the plan to the wire body. Unknown optional
// values are left to the server's defaults.
func buildAIProviderRequest(ctx context.Context, plan AIProviderResourceModel) (*client.AIProviderRequest, error) {
	// An unset key is sent as "" so that removing it from the config clears it.
	apiKey := knownString(plan.APIKey)
	req := &client.AIProviderRequest{
		Name:        plan.Name.ValueString(),
		UpstreamURL: plan.UpstreamURL.ValueStringPointer(),
		AuthType:    knownString(plan.AuthType),
		RoutingMode: knownString(plan.RoutingMode),
		APIKey:      &apiKey,
	}
	if len(plan.Headers) > 0 {
		req.Headers = headersToWire(plan.Headers)
	}
	if !plan.Capabilities.IsNull() && !plan.Capabilities.IsUnknown() {
		if d := plan.Capabilities.ElementsAs(ctx, &req.Capabilities, false); d.HasError() {
			return nil, fmt.Errorf("capabilities: %v", d)
		}
	}
	if !plan.SkipTLSVerification.IsUnknown() && !plan.SkipTLSVerification.IsNull() {
		req.SkipTLSVerification = plan.SkipTLSVerification.ValueBoolPointer()
	}
	if !plan.Enabled.IsUnknown() && !plan.Enabled.IsNull() {
		req.Enabled = plan.Enabled.ValueBoolPointer()
	}
	return req, nil
}

func aiProviderToModel(ctx context.Context, prior AIProviderResourceModel, p *client.AIProvider) (AIProviderResourceModel, error) {
	caps, d := types.SetValueFrom(ctx, types.StringType, p.Capabilities)
	if d.HasError() {
		return prior, fmt.Errorf("capabilities: %v", d)
	}
	m := AIProviderResourceModel{
		ID:                  types.Int64Value(int64(p.ProviderID)),
		NiceID:              types.StringValue(p.NiceID),
		Name:                types.StringValue(p.Name),
		Type:                types.StringValue(p.Type),
		UpstreamURL:         types.StringPointerValue(p.UpstreamURL),
		APIKey:              types.StringNull(),
		AuthType:            types.StringValue(p.AuthType),
		RoutingMode:         types.StringValue(p.RoutingMode),
		Capabilities:        caps,
		Headers:             headerModelsFromWire(prior.Headers, p.Headers),
		SkipTLSVerification: types.BoolValue(p.SkipTLSVerification),
		Enabled:             types.BoolValue(p.Enabled),
	}
	if p.APIKey != nil && *p.APIKey != "" {
		m.APIKey = types.StringValue(*p.APIKey)
	}
	return m, nil
}

func (r *AIProviderResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan AIProviderResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	body, err := buildAIProviderRequest(ctx, plan)
	if err != nil {
		resp.Diagnostics.AddError("Invalid AI provider", err.Error())
		return
	}
	body.Type = plan.Type.ValueString()
	if *body.APIKey == "" {
		body.APIKey = nil
	}
	created, err := r.client.CreateAIProvider(ctx, body)
	if err != nil {
		resp.Diagnostics.AddError("Failed to create AI provider", err.Error())
		return
	}
	state, err := aiProviderToModel(ctx, plan, created)
	if err != nil {
		resp.Diagnostics.AddError("Failed to read AI provider", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *AIProviderResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state AIProviderResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	got, err := r.client.GetAIProvider(ctx, int(state.ID.ValueInt64()))
	if err != nil {
		if errors.Is(err, client.ErrNotFound) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Failed to read AI provider", err.Error())
		return
	}
	state, err = aiProviderToModel(ctx, state, got)
	if err != nil {
		resp.Diagnostics.AddError("Failed to read AI provider", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *AIProviderResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan AIProviderResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	body, err := buildAIProviderRequest(ctx, plan)
	if err != nil {
		resp.Diagnostics.AddError("Invalid AI provider", err.Error())
		return
	}
	updated, err := r.client.UpdateAIProvider(ctx, int(plan.ID.ValueInt64()), body)
	if err != nil {
		resp.Diagnostics.AddError("Failed to update AI provider", err.Error())
		return
	}
	state, err := aiProviderToModel(ctx, plan, updated)
	if err != nil {
		resp.Diagnostics.AddError("Failed to read AI provider", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *AIProviderResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state AIProviderResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteAIProvider(ctx, int(state.ID.ValueInt64())); err != nil && !errors.Is(err, client.ErrNotFound) {
		resp.Diagnostics.AddError("Failed to delete AI provider", err.Error())
	}
}

func (r *AIProviderResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	id, err := strconv.ParseInt(req.ID, 10, 64)
	if err != nil {
		resp.Diagnostics.AddError("Invalid import ID", fmt.Sprintf("Expected a numeric AI provider ID, got: %q", req.ID))
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), id)...)
}
